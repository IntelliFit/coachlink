在卧推、俯卧撑、双杠臂屈伸、划船、引体这些动作里观察：

- 推类动作时，肩前侧是不是比胸肌更先不舒服。
- 拉类动作时，是不是总耸肩、肩胛不会自然上旋或后倾。
- 动作结束后，胸前深层紧张是不是反复出现。

