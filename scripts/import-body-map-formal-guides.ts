function nowStamp() {
  const d = new Date();
  const pad = (n: number) => String(n).padStart(2, '0');
  return `${d.getFullYear()}${pad(d.getMonth() + 1)}${pad(d.getDate())}_${pad(d.getHours())}${pad(d.getMinutes())}${pad(d.getSeconds())}`;
}

async function upsertGuide(serviceRoleSupabase: any, guide: FormalGuide, html: string) {
  const now = new Date().toISOString();
  const payload = {
    node_type: 'article',
    title: guide.title,
    slug: guide.slug,
    description: guide.description,
    icon: guide.pendingBodyMapHitbox ? 'AlertTriangle' : 'FileText',
    content: {
      body: html,
      tags: guide.tags,
      difficulty: guide.difficulty,
      source: 'body-map-system/content',
      source_topic: guide.displayName,
      source_topic_slug: guide.sourceTopicSlug,
      source_transcript_pack_slug: `body-map-transcript-pack-${guide.sourceTopicSlug}`,
      body_map_modes: guide.modes,
      body_map_import_status: guide.pendingBodyMapHitbox ? 'pending' : 'usable',
      pending_body_map_hitbox: guide.pendingBodyMapHitbox,
      content_level: 'formal-guide',
      import_version: IMPORT_VERSION,
    },
    body_region: guide.bodyRegions,
    difficulty: guide.difficulty,
    is_free: true,
    is_published: true,
    sort_order: guide.sortOrder,
    updated_at: now,
  };

  const { data: existing, error: existingError } = await serviceRoleSupabase
    .from('knowledge_nodes')
    .select('id')
    .eq('slug', guide.slug)
    .maybeSingle();

  if (existingError) throw existingError;

  if (existing?.id) {
    const { error } = await serviceRoleSupabase.from('knowledge_nodes').update(payload).eq('id', existing.id);
    if (error) throw error;
    return { action: 'updated' as const, id: existing.id };
  }

  const { data: inserted, error } = await serviceRoleSupabase
    .from('knowledge_nodes')
    .insert({
      ...payload,
      created_at: now,
    })
    .select('id')
    .single();

  if (error) throw error;

  const { error: closureError } = await serviceRoleSupabase
    .from('knowledge_node_closures')
    .upsert(
      {
        ancestor_id: inserted.id,
        descendant_id: inserted.id,
        depth: 0,
      },
      { onConflict: 'ancestor_id,descendant_id' },
    );
  if (closureError) throw closureError;

  return { action: 'inserted' as const, id: inserted.id };
}

