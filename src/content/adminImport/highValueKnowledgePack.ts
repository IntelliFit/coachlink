import type { AdminContentImportBundle, TrainingPlanTemplateImport } from "@/lib/adminContentImport";

function strength(
    actionName: string,
    sets: number,
    reps: string,
    intensity: string,
    restSeconds: number,
) {
    return {
        type: "no-filter",
        itemType: "STRENGTH",
        actionName,
        setName: actionName,
        params: {
            sets,
            reps,
            rest_seconds: restSeconds,
            intensity,
            "组数": sets,
            "次数": reps,
            "休息时间": restSeconds,
            "强度": intensity,
        },
    };
}

function habit(
    actionName: string,
    sets: number,
    reps: string,
    intensity: string,
    restSeconds = 45,
) {
    return {
        type: "no-filter",
        itemType: "HABIT",
        actionName,
        setName: actionName,
        params: {
            sets,
            reps,
            rest_seconds: restSeconds,
            intensity,
            "组数": sets,
            "次数": reps,
            "休息时间": restSeconds,
            "强度": intensity,
        },
    };
}

function trainingDay(dayIndex: number, note: string, actionSets: ReturnType<typeof strength>[]) {
    return { dayIndex, type: "training" as const, note, actionSets };
}

function restDay(dayIndex: number, note = "休息或轻量主动恢复。") {
    return { dayIndex, type: "rest" as const, note, actionSets: [] };
}

